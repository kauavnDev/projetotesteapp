import { readFile, access, readdir } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
const root=process.cwd();
const read=async p=>readFile(path.join(root,p),'utf8');
const checks=[];
function check(name,ok,detail=''){checks.push({name,ok:Boolean(ok),detail});}
const rootPkg=JSON.parse(await read('package.json'));
const apiPkg=JSON.parse(await read('apps/api/package.json'));
const mobilePkg=JSON.parse(await read('apps/mobile/package.json'));
const adminPkg=JSON.parse(await read('apps/admin/package.json'));
const schema=await read('apps/api/src/db/schema.ts');
const migration=await read('apps/api/drizzle/0000_forge_baseline.sql');
const auth=await read('apps/api/src/middleware/auth.ts');
const body=await read('apps/api/src/routes/body.ts');
const core=await read('apps/api/src/routes/core.ts');
const alarms=await read('apps/mobile/app/alarms.tsx');
check('pnpm monorepo configured',rootPkg.packageManager?.startsWith('pnpm@')&&rootPkg.devDependencies?.turbo);
check('Expo SDK 51 + Router + Reanimated',mobilePkg.dependencies?.expo?.startsWith('~51.')&&mobilePkg.dependencies?.['expo-router']&&mobilePkg.dependencies?.['react-native-reanimated']);
check('Hono + esbuild + Drizzle',apiPkg.dependencies?.hono&&apiPkg.devDependencies?.esbuild&&apiPkg.dependencies?.['drizzle-orm']);
check('Next.js 14 + Tailwind',adminPkg.dependencies?.next?.startsWith('14.')&&adminPkg.devDependencies?.tailwindcss);
check('Required database entities', ['users','habits','habit_logs','savings_entries','goals','points_ledger','quotes','body_photos','body_analyses','alarms','refresh_tokens','mind_entries'].every(t=>schema.includes(`pgTable("${t}"`)&&migration.includes(`TABLE IF NOT EXISTS ${t}`)));
check('Role derived from server allowlist',auth.includes('isAdminEmail(account.email)')&&auth.includes('users.active'));
check('Private photo ownership + content validation',body.includes('eq(bodyPhotos.userId,c.get("user").id)')&&body.includes('sniffImage')&&body.includes('Cache-Control":"private, no-store'));
check('AI requires explicit consent and configured key',body.includes('consent!==true')&&body.includes('OPENAI_API_KEY'));
check('Alarm exceptions tied to base alarm',alarms.includes('parentAlarmId')&&alarms.includes('overrideDate'));
check('No committed local environment file',!await access(path.join(root,'.env')).then(()=>true).catch(()=>false));
check('No public upload directory configured',!schema.includes('public/uploads'));
const failures=checks.filter(x=>!x.ok);
console.log(JSON.stringify({passed:checks.length-failures.length,total:checks.length,checks},null,2));
if(failures.length)process.exit(1);
